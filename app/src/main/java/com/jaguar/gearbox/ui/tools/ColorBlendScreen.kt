@Composable
fun ColorBlendScreen(onNavigateBack: () -> Unit) {
    val context = LocalContext.current
    var firstText by rememberSaveable { mutableStateOf("#FF0000") }
    var secondText by rememberSaveable { mutableStateOf("#0000FF") }
    var weightText by rememberSaveable { mutableStateOf("50") }
    var generated by remember { mutableStateOf<RgbColor?>(null) }
    var restoreError by remember { mutableStateOf(false) }
    val first = parseOpaqueHex(firstText)
    val second = parseOpaqueHex(secondText)
    val inputs = mapOf("firstHex" to firstText, "secondHex" to secondText, "weight" to weightText)
    val setup = parseColorBlendSnapshot(inputs)
    val weight = weightText.takeIf { Regex("0|[1-9][0-9]?|100").matches(it) }?.toIntOrNull()
    val output = generated?.let { context.getString(R.string.blend_output, colorBlendHex(it), it.red, it.green, it.blue) }
    fun edited() { generated = null; restoreError = false }
    fun restore(values: Map<String, String>) {
        val saved = parseColorBlendSnapshot(values)
        if (saved == null) { restoreError = true; return }
        firstText = saved.firstHex; secondText = saved.secondHex; weightText = saved.weight.toString()
        generated = null; restoreError = false
    }
    val history = rememberToolHistory(
        route = Tools.ROUTE_COLOR_BLEND, inputs = inputs, output = output,
        modeInputs = if (setup != null) inputs else emptyMap(),
        onRestore = ::restore, onRestoreMode = ::restore,
        resultRequiresExplicitAction = true,
        // Only the user's remembered-result preference can hydrate a completed local result.
        // Explicit imports and presets above remain input-only and require Blend.
        onRestoreLastResult = { values ->
            val saved = parseColorBlendSnapshot(values)
            if (saved == null) restoreError = true
            else {
                // Keep validated source spelling so hydration fingerprints still match
                // older lowercase records and cannot recreate cleared history/modes.
                firstText = values.getValue("firstHex")
                secondText = values.getValue("secondHex")
                weightText = values.getValue("weight")
                restoreError = false
                generated = blendEncodedSrgb(requireNotNull(parseOpaqueHex(saved.firstHex)),
                    requireNotNull(parseOpaqueHex(saved.secondHex)), saved.weight)
            }
        },
        restoredResultRequiresExplicitAction = { false },
    )
    ToolScaffold(stringResource(R.string.blend_title), Tools.byRoute(Tools.ROUTE_COLOR_BLEND)!!.icon,
        onNavigateBack, history = history) {
        AdaptiveToolLayout(input = {
            OutlinedTextField(firstText, { firstText = it; edited() }, singleLine = true,
                label = { Text(stringResource(R.string.blend_first)) }, isError = first == null,
                supportingText = { if (first == null) Text(stringResource(R.string.blend_hex_error)) }, modifier = Modifier.fillMaxWidth())
            first?.let { BlendSwatch(it, stringResource(R.string.blend_first_swatch)) }
            OutlinedTextField(secondText, { secondText = it; edited() }, singleLine = true,
                label = { Text(stringResource(R.string.blend_second)) }, isError = second == null,
                supportingText = { if (second == null) Text(stringResource(R.string.blend_hex_error)) }, modifier = Modifier.fillMaxWidth())
            second?.let { BlendSwatch(it, stringResource(R.string.blend_second_swatch)) }
            OutlinedTextField(weightText, { weightText = it; edited() }, singleLine = true,
                label = { Text(stringResource(R.string.blend_weight)) }, isError = weight == null,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                supportingText = { if (weight == null) Text(stringResource(R.string.blend_weight_error)) }, modifier = Modifier.fillMaxWidth())
            val sliderLabel = stringResource(R.string.blend_weight)
            Slider(value = (weight ?: 50).toFloat(), onValueChange = { weightText = it.roundToInt().toString(); edited() },
                valueRange = 0f..100f, steps = 99, modifier = Modifier.semantics { contentDescription = sliderLabel })
            if (weight != null) Text(stringResource(R.string.blend_weight_summary, 100 - weight, weight))
            Button(enabled = setup != null, onClick = {
                if (first != null && second != null && weight != null) {
                    generated = blendEncodedSrgb(first, second, weight); restoreError = false
                }
            }, modifier = Modifier.fillMaxWidth()) { Text(stringResource(R.string.blend_action)) }
            if (restoreError) Text(stringResource(R.string.blend_restore_error), color = MaterialTheme.colorScheme.error)
            Text(stringResource(R.string.blend_explanation), style = MaterialTheme.typography.bodySmall)
            Text(stringResource(R.string.blend_endpoints), style = MaterialTheme.typography.bodySmall)
        }, result = {
            Text(stringResource(R.string.blend_output_heading), style = MaterialTheme.typography.titleLarge)
            generated?.let { BlendSwatch(it, stringResource(R.string.blend_result_swatch)) }
            if (output != null) ResultCard(output) else Text(stringResource(R.string.blend_empty))
            ToolActions(onCopy = { output?.let { context.copyToClipboard(context.getString(R.string.blend_title), it) } },
                onShare = { output?.let { context.shareText(it) } },
                onClear = { firstText = ""; secondText = ""; weightText = "50"; edited() },
                resultEnabled = output != null, clearEnabled = firstText.isNotEmpty() || secondText.isNotEmpty() || weightText != "50" || generated != null)
        })
    }
}

@Composable
private fun BlendSwatch(color: RgbColor, label: String) {
    val description = stringResource(R.string.blend_swatch, label, colorBlendHex(color), color.red, color.green, color.blue)
    Box(Modifier.fillMaxWidth().padding(vertical = 8.dp).height(64.dp)
        .background(Color(color.red, color.green, color.blue), MaterialTheme.shapes.small)
        .semantics { contentDescription = description })
}
